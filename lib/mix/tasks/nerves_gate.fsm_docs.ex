defmodule Mix.Tasks.NervesGate.FsmDocs do
  @moduledoc "Generates lifecycle architecture diagrams from executable Finitomata declarations."

  use Mix.Task

  @shortdoc "Generate docs/lifecycle-machines.md"

  @subsystems [
    {"Internet", NervesGate.Internet},
    {"Tailnet", NervesGate.Tailnet},
    {"SSH", NervesGate.SSH},
    {"Cluster", NervesGate.Cluster},
    {"Cluster peer", NervesGate.Cluster.Peer},
    {"Subnet router", NervesGate.SubnetRouter},
    {"Commissioning", NervesGate.Commissioning},
    {"Gateway configuration", NervesGate.Gateway.Configuration},
    {"Device-state replica", NervesGate.DeviceState.Replica}
  ]

  @impl Mix.Task
  def run(_arguments) do
    Mix.Task.run("compile")

    content =
      [header(), dependency_overview() | Enum.map(@subsystems, &subsystem_section/1)]
      |> Enum.map(&String.trim/1)
      |> Enum.join("\n\n")

    File.mkdir_p!("docs")
    File.write!("docs/lifecycle-machines.md", content <> "\n")
    Mix.shell().info("Generated docs/lifecycle-machines.md from Finitomata graphs")
  end

  defp header do
    """
    # Lifecycle machines

    This file is generated by `mix nerves_gate.fsm_docs`. Each Mermaid diagram is
    emitted from the same `@fsm` declaration compiled by Finitomata. Edit the subsystem
    entry module, not this file, then regenerate it.
    """
  end

  defp dependency_overview do
    """
    ## Dependency overview

    ```mermaid
    flowchart TD
      Internet[Internet contract]
      Tailnet --> SSH
      Tailnet --> Cluster
      Tailnet --> SubnetRouter
      Cluster --> PeerMachines[Peer machines]
      Configuration[Gateway.Configuration] --> Internet
      Configuration --> Tailnet
      Configuration --> SSH
      Configuration --> Cluster
      Configuration --> SubnetRouter
      Internet --> DeviceState[DeviceState.State]
      Tailnet --> DeviceState
      SSH --> DeviceState
      Cluster --> DeviceState
      SubnetRouter --> DeviceState
      DeviceState --> Replicas[Replica machines]
    ```
    """
  end

  defp subsystem_section({title, module}) do
    """
    ## #{title}

    Source: `#{inspect(module)}`

    ```mermaid
    stateDiagram-v2
    #{indent(module.graph())}
    ```
    """
  end

  defp indent(graph) do
    graph
    |> String.trim()
    |> String.split("\n")
    |> Enum.map_join("\n", &"  #{&1}")
  end
end
